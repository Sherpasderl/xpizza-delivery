// Customer app — self-hosted fonts, no reflow (PLAN-capp-S7a r3.3 F4; owner rule: no pop-in from our code). Static guards over the
// REAL files the page ships: index.html, shell.html, figtree-fonts.css, capp.css, fonts-figtree/. The CLS=0 proof in a real browser is
// review/capp-perf/capp-perf.cdp.mjs.
// OWNER 11-13 / 11-14 (PLAN-font-figtree-r0): ONE typeface everywhere — Figtree. The capp consumes the platform pipeline's GENERATED
// output (platform/fonts/build-fonts.mjs → figtree-fonts.css + fonts-figtree/, manifest entry `capp`), merged from feat/fonts-figtree-pin;
// exactly ONE preload (the latin variable woff2, manifest `preload`); Red Hat is gone from every shipped file.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const read = (f) => readFileSync(join(HERE, f), 'utf8');
const PAGES = ['index.html', 'shell.html'];
const fontsCss = read('figtree-fonts.css'), appCss = read('capp.css');
const faces = [...fontsCss.matchAll(/@font-face\{([^}]*)\}/g)].map((m) => m[1]);
const family = (f) => (f.match(/font-family:'([^']+)'/) || [])[1];
const primary = faces.filter((f) => /url\(fonts-figtree\//.test(f));
const fallback = faces.filter((f) => /src:local\(/.test(f));
const STACK = "'Figtree','FigtreeFallback','FigtreeFallbackRoboto',";

test('the page loads NO third-party font (no Google Fonts swap)', () => {
  for (const f of readdirSync(HERE).filter((n) => /\.(html|css)$/.test(n))) {
    assert.doesNotMatch(read(f), /fonts\.(googleapis|gstatic)\.com/, `🔴 ${f} still loads Google Fonts`);
  }
});

test('figtree-fonts.css is the pipeline\'s GENERATED file: two variable faces (latin + latin-ext, 300–900), font-display:optional', () => {
  assert.match(fontsCss, /^\/\* GENERATED by platform\/fonts\/build-fonts\.mjs — do not edit/, 'the generated output, never a hand copy');
  assert.equal(primary.length, 2, 'Figtree latin + latin-ext');
  for (const f of primary) {
    assert.equal(family(f), 'Figtree');
    assert.match(f, /font-display:optional/, `🔴 FIG-OPT: ${f.slice(0, 80)} would swap after paint`);
    assert.match(f, /font-weight:300 900/, 'the variable range — 550 / 650 / 750 are real weights');
  }
  assert.doesNotMatch(fontsCss, /font-display:\s*(swap|fallback|block|auto)/, 'no other display policy anywhere');
});

test('exactly ONE preload on each page — the latin variable woff2 — as=font, woff2, crossorigin, before the stylesheets', () => {
  const latin = primary.filter((f) => /U\+0000-00FF/.test(f)).map((f) => f.match(/url\(([^)]+)\)/)[1]);
  assert.deepEqual(latin, ['fonts-figtree/figtree-latin.8330490a01.woff2'], 'premise: the pinned latin file');
  for (const p of PAGES) {
    const html = read(p);
    const pre = [...html.matchAll(/<link rel="preload"([^>]*)>/g)].map((m) => m[1]);
    assert.deepEqual(pre.map((a) => a.match(/href="([^"]+)"/)[1]), latin, `🔴 FIG-PRELOAD: ${p} preloads exactly the latin woff2 (manifest: ONE preload)`);
    for (const a of pre) { assert.match(a, /as="font"/); assert.match(a, /type="font\/woff2"/); assert.match(a, /\bcrossorigin\b/, 'font preloads need crossorigin or they are not reused'); }
    const at = (s) => html.indexOf(s);
    assert.ok(at('rel="preload"') < at('figtree-fonts.css') && at('figtree-fonts.css') < at('capp.css'), `${p}: preload → figtree-fonts.css → capp.css`);
    assert.ok(!/capp-fonts\.css|red-hat/i.test(html), `🔴 FIG-GONE: ${p} still names the Red Hat files`);
  }
});

test('fonts-figtree/: every file is referenced, every reference exists, each name carries its content hash; immutable cache; OFL', () => {
  const files = readdirSync(join(HERE, 'fonts-figtree')).filter((n) => n.endsWith('.woff2')).sort();
  const refs = [...fontsCss.matchAll(/url\(fonts-figtree\/([^)]+)\)/g)].map((m) => m[1]).sort();
  assert.deepEqual(refs, files);
  for (const n of files) {
    const h = createHash('sha256').update(readFileSync(join(HERE, 'fonts-figtree', n))).digest('hex').slice(0, 10);
    assert.equal(n.split('.').slice(-2, -1)[0], h, `🔴 ${n}: the name's hash is not its bytes' hash`);
  }
  assert.match(read('fonts-figtree/OFL.txt'), /SIL Open Font License, Version 1\.1/, 'the OFL travels with the fonts');
  assert.match(read('netlify.toml'), /for = "\/fonts-figtree\/\*"[\s\S]*?Cache-Control = "public, max-age=31536000, immutable"/, '🔴 FIG-CACHE: the hashed files cached forever');
});

test('every fallback face is metric-matched (size-adjust + ascent/descent/line-gap overrides), two bands each', () => {
  assert.equal(fallback.length, 4);
  for (const f of fallback) for (const d of ['size-adjust', 'ascent-override', 'descent-override', 'line-gap-override']) assert.match(f, new RegExp(`${d}:[\\d.]+%`), `${family(f)} lacks ${d}`);
  assert.deepEqual([...new Set(fallback.map(family))].sort(), ['Figtree Fallback', 'Figtree Fallback Roboto']);
});

test('every font stack in capp.css is Figtree + its two metric-matched fallbacks; Red Hat is gone from every shipped file', () => {
  const stacks = [...appCss.matchAll(/--[\w-]+:\s*('[^';]+'[^;]*);/g)].map((m) => m[1]).filter((s) => /^'(Figtree|Red Hat)/.test(s));
  assert.ok(stacks.length >= 1, 'premise: the stacks');
  for (const s of stacks) assert.ok(s.replace(/\s+/g, '').startsWith(STACK), `🔴 FIG-STACK: ${s}`);
  for (const f of readdirSync(HERE).filter((n) => /\.(html|css|js)$/.test(n) && !n.includes('.test.'))) assert.doesNotMatch(read(f), /Red Hat|red-hat/, `🔴 FIG-GONE: ${f} still names Red Hat`);
  assert.equal(existsSync(join(HERE, 'fonts')), false, '🔴 FIG-GONE: the Red Hat fonts/ folder is deleted');
  assert.equal(existsSync(join(HERE, 'capp-fonts.css')), false, '🔴 FIG-GONE: capp-fonts.css is deleted');
});
