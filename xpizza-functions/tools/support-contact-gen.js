'use strict';
// Sherpa support's WhatsApp for the PORTAL (Inicio «Ayuda», owner 11-14) — derived from the ONE source the customer app reads:
// platform/sites.json → the platform orders deployment's runtime.support_whatsapp (E.164, validated by platform-manifest.js).
// sync-client.js writes xpizza-portal/support-contact.js from it; support-contact.test.mjs pins the file to this function's output.
const SHAPE = /^\+[1-9]\d{7,14}$/;
function supportWhatsappOf(sites) {
  const d = (sites && Array.isArray(sites.deployments) ? sites.deployments : []).find((x) => x && x.app === 'orders' && x.context === 'platform');
  const v = d && d.runtime ? d.runtime.support_whatsapp : undefined;
  return typeof v === 'string' && SHAPE.test(v) ? v : null;
}
function supportContactSource(sites) {
  const v = supportWhatsappOf(sites);
  return '// GENERATED by xpizza-functions/tools/sync-client.js — do not edit. Sherpa support\'s WhatsApp (E.164), from the ONE source:\n'
    + '// platform/sites.json → the platform orders deployment\'s runtime.support_whatsapp (validated by platform-manifest.js).\n'
    + `export const SUPPORT_WHATSAPP = ${v === null ? 'null' : `'${v}'`};\n`;
}
module.exports = { supportWhatsappOf, supportContactSource };
