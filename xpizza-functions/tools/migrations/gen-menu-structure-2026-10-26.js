'use strict';
// PLAN 4 (bake from published) r3 §8.2 — GENERATES the reviewed data file tools/migrations/2026-10-26-menu-structure.json
// from the bootstrap literals the forms carry at 486f71aa. The literals are read from the PINNED commit, not the working
// tree, so the GATED commit that deletes their runtime use (and the literal icon maps) cannot change what this produces.
//
// What it authors (only fields the migration ADDS when absent — see tools/migrate-menu-structure.js):
//   <rid>.structure.badge_priority                     = that form's TAG_PRIORITY (a form that declares none authors none)
//   x_pizza.items[<name>].display.reward_icon          = buildRedeemCatalog's name-keyed ICON map
//   la_musa.items[<id>].display.reward_icon            = buildRedeemCatalog's category → icon map (CAT[cat][1]), for the
//                                                         dishes that picker offers (a CAT category, not beer_*)
//   la_musa.extras[<id>].display.reward_icon           = the 'rice' the picker hard-codes for its acompañamientos
//   x_pizza.items['Nutella'].display.extras_policy     = 'none' (the renderer's `dish.name === 'Nutella'` check, as data)
//
// Run:  node tools/migrations/gen-menu-structure-2026-10-26.js            (prints the file)
//       node tools/migrations/gen-menu-structure-2026-10-26.js --write    (writes it)
//       node tools/migrations/gen-menu-structure-2026-10-26.js --check    (exit 1 when the committed file differs)
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { readLiteral, pricingKeyOf, extrasKeyOf } = require('../../catalog/form-menu-source');
const { REWARD_ICONS } = require('../../catalog/reward-icons');

const PIN = '486f71aa';
const FORMS = { x_pizza: 'xpizza-orders/index.html', la_musa: 'la-musa-orders/index.html' };
const OUT = path.join(__dirname, '2026-10-26-menu-structure.json');
const formAt = (rid) => execFileSync('git', ['show', `${PIN}:${FORMS[rid]}`], { cwd: __dirname, encoding: 'utf8', maxBuffer: 1 << 27 });

// A `const NAME={…}` declared INSIDE buildRedeemCatalog (no spaces, so the bootstrap reader's `const NAME = {` does not
// see it). Sliced by brace balance from that function's body only; the literal holds no braces inside strings.
function redeemLiteral(src, name) {
  const fnAt = src.indexOf('function buildRedeemCatalog(){');
  if (fnAt < 0) throw new Error(`gen_no_redeem_catalog: ${name}`);
  const at = src.indexOf(`const ${name}={`, fnAt);
  if (at < 0 || at > src.indexOf('\n}\n', fnAt)) throw new Error(`gen_no_literal: ${name} in buildRedeemCatalog`);
  const open = src.indexOf('{', at);
  let depth = 0;
  for (let i = open; i < src.length; i += 1) {
    if (src[i] === '{') depth += 1;
    else if (src[i] === '}') { depth -= 1; if (depth === 0) return new Function(`return (${src.slice(open, i + 1)})`)(); }
  }
  throw new Error(`gen_unbalanced: ${name}`);
}
const icon = (v, where) => { if (!REWARD_ICONS.includes(v)) throw new Error(`gen_icon_outside_set: ${where} → ${v}`); return v; };

function generate() {
  const out = { _doc: `GENERATED by tools/migrations/gen-menu-structure-2026-10-26.js from the forms at ${PIN} — reviewed data for tools/migrate-menu-structure.js (PLAN 4 r3 §8.2). The migration ADDS a field only where it is absent; a present, different value is a merchant edit and is preserved and reported.`, restaurants: {} };
  for (const rid of Object.keys(FORMS).sort()) {
    const src = formAt(rid);
    const r = { structure: {}, items: {}, extras: {} };
    const dishes = readLiteral(src, 'MENU');
    try { const p = readLiteral(src, 'TAG_PRIORITY'); if (Array.isArray(p) && p.length) r.structure.badge_priority = p; } catch (e) {
      if (!/^form_literal_not_found:/.test(String(e && e.message))) throw e;
    }
    if (rid === 'x_pizza') {
      const ICON = redeemLiteral(src, 'ICON');
      for (const d of dishes) {
        if (Object.prototype.hasOwnProperty.call(ICON, d.name)) {
          (r.items[pricingKeyOf(rid, d)] = r.items[pricingKeyOf(rid, d)] || { display: {} }).display.reward_icon = icon(ICON[d.name], `${rid}/${d.name}`);
        }
      }
      for (const name of Object.keys(ICON)) {
        if (!dishes.some((d) => d.name === name)) throw new Error(`gen_icon_for_unknown_dish: ${rid}/${name}`);
      }
      const nut = dishes.find((d) => d.name === 'Nutella');
      if (!nut) throw new Error('gen_no_nutella: x_pizza');
      (r.items[pricingKeyOf(rid, nut)] = r.items[pricingKeyOf(rid, nut)] || { display: {} }).display.extras_policy = 'none';
    } else {
      const CAT = redeemLiteral(src, 'CAT');
      for (const d of dishes) {
        if (String(d.id).indexOf('beer_') === 0 || !Object.prototype.hasOwnProperty.call(CAT, d.cat)) continue;
        r.items[pricingKeyOf(rid, d)] = { display: { reward_icon: icon(CAT[d.cat][1], `${rid}/${d.cat}`) } };
      }
      const fnBody = src.slice(src.indexOf('function buildRedeemCatalog(){'));
      if (!/e\.cat!=='Acompañamientos'\) return; out\.push\(\{[^}]*icon:'rice' \}\)/.test(fnBody.slice(0, fnBody.indexOf('\n}\n')))) {
        throw new Error('gen_acompanamientos_shape_moved: la_musa');
      }
      for (const e of readLiteral(src, 'EXTRAS')) {
        if (e.cat === 'Acompañamientos') r.extras[extrasKeyOf(rid, e)] = { display: { reward_icon: icon('rice', `${rid}/extra ${e.id}`) } };
      }
    }
    for (const k of ['structure', 'items', 'extras']) if (!Object.keys(r[k]).length) delete r[k];
    out.restaurants[rid] = r;
  }
  return `${JSON.stringify(out, null, 1)}\n`;
}

module.exports = { generate, PIN, OUT };

if (require.main === module) {
  const text = generate();
  if (process.argv.includes('--write')) { fs.writeFileSync(OUT, text); console.log(`wrote ${path.relative(process.cwd(), OUT)}`); }
  else if (process.argv.includes('--check')) {
    const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === text;
    console.log(same ? 'menu-structure data: current' : 'menu-structure data: STALE — regenerate with --write and review the diff');
    process.exit(same ? 0 : 1);
  } else process.stdout.write(text);
}
