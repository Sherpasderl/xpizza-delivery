'use strict';
/* R3 P1-b — THE BRANCH-COVERAGE LIST (PLAN-R3-P1 §3c; DESIGN-R3-P1B.md). Every census site that a REQUIRED P1 cell
 * obligates is listed with:
 *   · planned   — the (scenario, brand, LP) cells that require it (derived from matrix.json — the scenarios DESIGNED to
 *                 reach it);
 *   · exercised — the run contexts of a committed gate-B baseline (contract/p1-hits.json) that actually hit it.
 * A site with planned cells but no exercised hit is PLANNED (visible, not credit). A site no planned P1 scenario can reach
 * needs a reviewed GAP (contract/p1-branch-gaps.json, with a reason). Planned and exercised are never conflated (codex r3
 * P2). The list is GENERATED (`node contract/branch-coverage.js --write`) and must equal the committed file.
 */
const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, 'p1-branch-coverage.json');
const GAPS = path.join(__dirname, 'p1-branch-gaps.json');
const P1 = ['S1', 'S1t-a', 'S1t-b', 'S1t-c', 'S1a-on', 'S1a-off', 'S2', 'S3', 'S4', 'S13', 'S14-omitted', 'S14-empty', 'S14-efectivo', 'S14-bitcoin', 'S17d', 'S17p'];

function build({ matrix = JSON.parse(fs.readFileSync(path.join(__dirname, 'matrix.json'), 'utf8')), hits = JSON.parse(fs.readFileSync(path.join(__dirname, 'p1-hits.json'), 'utf8')) } = {}) {
  const planned = new Map();
  for (const c of matrix.cells) {
    if (c.status !== 'required' || !P1.includes(c.S)) continue;
    for (const i of c.sites || []) { const s = matrix.siteObligations[i].site; if (!planned.has(s)) planned.set(s, new Set()); planned.get(s).add(`${c.S}|${c.brand}|${c.lp}`); }
  }
  // a baseline context names its scenario / brand / phase ('S1/x_pizza/new'); the form phase ('…/form') is the customer's
  // pre-submit part of LP new. 'boot' (fixture setup) names no scenario and never counts as exercised.
  const cellOfContext = (ctx) => { const m = /^([^/]+)\/([^/]+)\/([^/]+)$/.exec(ctx); return m ? `${m[1]}|${m[2]}|${m[3] === 'form' ? 'new' : m[3]}` : null; };
  const hitIn = new Map();
  for (const [ctx, sites] of Object.entries(hits.contexts || {})) for (const s of sites) { if (!hitIn.has(s)) hitIn.set(s, []); hitIn.get(s).push(ctx); }
  const sites = {};
  for (const s of [...planned.keys()].sort()) {
    const p = [...planned.get(s)].sort();
    // compress: scenario → { brand: [lp] }
    const byS = {}; for (const k of p) { const [S, b, lp] = k.split('|'); ((byS[S] = byS[S] || {})[b] = (byS[S][b] || [])).push(lp); }
    // EXERCISED cites a baseline hit in a NAMED planned (scenario, brand, LP) — a hit elsewhere is not credit (codex P1-b r1)
    const exercised = (hitIn.get(s) || []).map((ctx) => ({ ctx, cell: cellOfContext(ctx) })).filter((x) => x.cell && planned.get(s).has(x.cell)).map((x) => `${x.cell} @ ${x.ctx}`).sort();
    sites[s] = { planned: byS, exercised };
  }
  const counts = { sites: Object.keys(sites).length, exercised: Object.values(sites).filter((x) => x.exercised.length).length };
  counts.plannedOnly = counts.sites - counts.exercised;
  return { _doc: 'GENERATED by contract/branch-coverage.js from matrix.json (P1 required cells) + p1-hits.json — do not edit by hand. planned = the designed (scenario, brand, LP) cells; exercised = baseline contexts that hit the site.', counts, sites };
}
const write = (doc = build()) => fs.writeFileSync(OUT, JSON.stringify(doc, null, 1) + '\n');

module.exports = { build, write, OUT, GAPS, P1 };
if (require.main === module) { const d = build(); console.log(JSON.stringify(d.counts)); if (process.argv.includes('--write')) { write(d); console.log('wrote contract/p1-branch-coverage.json'); } }
