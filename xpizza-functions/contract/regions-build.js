'use strict';
/* R3 P1 §4b — THE TERMINAL-REGION INVENTORY (codex P1 plan r3 P1-1). An output is `file#function`; it is NOT necessarily one
 * observable. Every CONSUMER CALL SITE of an output (a call `fn(…)` / `X.fn(…)` in its scope, named with the census's own
 * function naming) is a REGION: `paymentRowHtml` called from the driver active card AND the queue detail sheet is two
 * regions, each its own gate A cell. An output with no consumer in scope (an entry point / handler) or an inline callback
 * (`fn>anon`) is one region: itself.
 *
 * The inventory is GENERATED; each region's review lives in contract/outputs/registry.json:
 *   terminal { observable, action }  — compared in gate A at its own observable (exposed by `action`);
 *   via { target, reason }           — not separately visible: its effect is asserted at region `target`;
 *   pending                          — inventoried, adapter not built yet (a required gate A cell in an enforced slice → RED).
 * The guard (region.guard) requires the registry's keys to EQUAL the generated inventory: a new consumer call site of any
 * output without a registry entry → RED.
 * `node contract/regions-build.js --write` regenerates contract/regions.json.
 */
const fs = require('fs');
const path = require('path');
const { sources, walk, parseUnit } = require('./census');

const OUT = path.join(__dirname, 'regions.json');
const REGISTRY = path.join(__dirname, 'outputs', 'registry.json');

function outputsOf(matrix) {
  const outs = new Set(matrix.siteObligations.map((o) => o.output));
  // an output assertion is `R3:<R>:<fact…>:[@!]<file#fn>` (a DISPLAY fact contains ':') — the output is after the LAST :@ / :!
  for (const c of matrix.cells) for (const a of c.outputs || []) { const m = /:[@!]([^:]*)$/.exec(a); if (m) outs.add(m[1]); }
  return [...outs].sort();
}

function build(matrix = JSON.parse(fs.readFileSync(path.join(__dirname, 'matrix.json'), 'utf8'))) {
  const units = sources(); const byScope = new Map();
  for (const u of units) { if (!byScope.has(u.scope)) byScope.set(u.scope, []); byScope.get(u.scope).push(u); }
  const unitScope = new Map(units.map((u) => [u.file, u.scope]));
  const calls = new Map();   // unit file → [{ name, caller, line }]
  const callsIn = (u) => {
    if (calls.has(u.file)) return calls.get(u.file);
    const out = [];
    walk(parseUnit(u), (node, fn) => {
      if (node.type !== 'CallExpression') return;
      const c = node.callee;
      const name = c.type === 'Identifier' ? c.name : (c.type === 'MemberExpression' && !c.computed ? c.property.name : null);
      if (name) out.push({ name, caller: fn || '<top>', line: node.loc.start.line + u.lineOffset });
    });
    calls.set(u.file, out); return out;
  };
  const regions = []; const problems = [];
  for (const o of outputsOf(matrix)) {
    const i = o.lastIndexOf('#'); const file = o.slice(0, i); const fn = o.slice(i + 1);
    // an unsited output named `dir/index.html#fn` (matrix-spec dispositions) lives in one of that page's inline units: its scope is the page dir
    const scope = unitScope.get(file) || (/\/index\.html$/.test(file) && byScope.has(file.split('/')[0]) ? file.split('/')[0] : null);
    if (!scope) { problems.push(`output ${o}: its unit is not a census unit`); continue; }
    if (fn.includes('>')) { regions.push({ output: o, region: `${o}@self`, consumer: null, why: 'inline callback — its own region' }); continue; }
    const cons = new Map();
    for (const u of byScope.get(scope)) for (const c of callsIn(u)) if (c.name === fn) { const k = `${u.file}#${c.caller}`; if (!cons.has(k)) cons.set(k, c.line); }
    if (!cons.size) { regions.push({ output: o, region: `${o}@self`, consumer: null, why: 'no consumer in scope — an entry point / handler / exported surface' }); continue; }
    for (const [k, line] of [...cons].sort()) regions.push({ output: o, region: `${o}@${k}`, consumer: k, line });
  }
  return { problems, doc: { _doc: 'GENERATED by contract/regions-build.js from matrix.json + the census units — do not edit by hand.', counts: { outputs: new Set(regions.map((r) => r.output)).size, regions: regions.length, multiConsumerOutputs: Object.values(regions.reduce((m, r) => ((m[r.output] = (m[r.output] || 0) + 1), m), {})).filter((n) => n > 1).length }, regions } };
}

module.exports = { build, OUT, REGISTRY, outputsOf };

if (require.main === module) {
  const { problems, doc } = build();
  console.log(JSON.stringify(doc.counts));
  if (problems.length) { console.error(problems.slice(0, 20).join('\n')); process.exitCode = 1; }
  if (process.argv.includes('--write')) { fs.writeFileSync(OUT, `{\n "_doc": ${JSON.stringify(doc._doc)},\n "counts": ${JSON.stringify(doc.counts)},\n "regions": [\n${doc.regions.map((r) => '  ' + JSON.stringify(r)).join(',\n')}\n ]\n}\n`); console.log('wrote contract/regions.json'); }
}
